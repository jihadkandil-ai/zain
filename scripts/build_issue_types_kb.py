def split_path(path: str) -> tuple[str, str, str]:
    parts = [p.strip() for p in path.split(">")]
    if len(parts) == 1:
        return parts[0], "", parts[0]
    if len(parts) == 2:
        return parts[0], parts[1], parts[1]
    return parts[0], parts[1], " > ".join(parts[2:])


def slugify(path: str) -> str:
    s = path.lower()
    s = re.sub(r"[^a-z0-9\u0600-\u06ff]+", "_", s)
    return s.strip("_")[:120]


def main() -> None:
    issues = []
    for path, use_case, includes, excludes, keywords in RAW:
        cat, sub, itype = split_path(path)
        issues.append(
            {
                "id": slugify(path),
                "path": path,
                "issue_category": cat,
                "sub_category": sub,
                "issue_type": itype,
                "use_case": use_case,
                "includes": includes,
                "does_not_include": excludes,
                "keywords": keywords,
            }
        )

    payload = {
        "version": 1,
        "source": "[Customer] Issue Types",
        "total": len(issues),
        "tips": [
            "Focus on the primary reason for contact",
            "Always link correct issue type to interaction type",
            "Consider the customer's emotional state",
            "When in doubt, consult with team lead",
            "In reopen/new issue/update cases, adjust issue type if needed",
        ],
        "fields": [
            "Issue Category (Level 1)",
            "Sub Category (Level 2)",
            "Issue type (Level 3)",
        ],
        "issue_types": issues,
    }
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT} total={len(issues)}")


